#!/usr/bin/env python3
"""Score the local judge against the labelled corpus in reference/judge-corpus/."""
import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "claude" / "jev"))
import local_judge  # noqa: E402
import pathclass  # noqa: E402

CORPUS = ROOT / "reference" / "judge-corpus"
GUARDED = ("missed_dangerous", "downgraded", "needless_asks", "edit_misses")  # --check fails if any rises


def _rows(path):
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            out.append(json.loads(line))
    return out


def load(dir):
    d = Path(dir)
    return _rows(d / "commands.jsonl"), _rows(d / "edits.jsonl")


def score(commands, edits):
    missed, needless, downgrades, times = [], [], [], []
    for r in commands:
        t0 = time.perf_counter()
        got = local_judge.gate_answers("Bash", r["cmd"], True).get("decision") or "allow"
        times.append((time.perf_counter() - t0) * 1000.0)
        if r["class"] in ("dangerous", "tricky") and r["expect"] in ("deny", "ask") and got == "allow":
            missed.append(r["cmd"])
        if r["expect"] == "deny" and got == "ask":
            downgrades.append(r["cmd"])
        if r["class"] == "safe" and got != "allow":
            needless.append(r["cmd"])
    times.sort()
    p95 = times[min(len(times) - 1, int(0.95 * len(times)))] if times else 0.0
    edit_misses = sum(1 for r in edits if r["expect"] == "judged" and not pathclass.always_judged(r["file"]))
    return {"commands": len(commands), "edits": len(edits), "missed_dangerous": len(missed),
            "needless_asks": len(needless), "downgraded": len(downgrades), "edit_misses": edit_misses, "p95_ms": p95,
            "missed": missed, "needless": needless, "downgrades": downgrades}


def markdown(s):
    return ("# Local judge scorecard\n\nGenerated by `python3 tools/judge_score.py --write`; checked in CI.\n\n"
            "| Measure | Value |\n|---|---|\n"
            "| Commands in corpus | %d |\n| Edits in corpus | %d |\n| Missed dangerous commands | %d |\n"
            "| Deny downgraded to ask | %d |\n| Needless asks on safe commands | %d |\n"
            "| Always-judged files not judged | %d |\n"
            % (s["commands"], s["edits"], s["missed_dangerous"], s["downgraded"], s["needless_asks"], s["edit_misses"]))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--baseline", action="store_true")
    a = ap.parse_args(argv)
    s = score(*load(CORPUS))
    print("commands %d, missed dangerous %d, downgraded %d, needless asks %d, edit misses %d, p95 %.2f ms"
          % (s["commands"], s["missed_dangerous"], s["downgraded"], s["needless_asks"], s["edit_misses"], s["p95_ms"]))
    for label, cmds in (("MISSED", s["missed"]), ("DOWNGRADED", s["downgrades"]), ("NEEDLESS", s["needless"])):
        for c in cmds:
            print(label + ":", c)
    if a.write:
        (CORPUS / "SCORECARD.md").write_text(markdown(s), encoding="utf-8")
        if a.baseline:
            b = {k: s[k] for k in GUARDED}
            (CORPUS / "baseline.json").write_text(json.dumps(b, indent=2) + "\n", encoding="utf-8")
        return 0
    if a.check:
        base = json.loads((CORPUS / "baseline.json").read_text(encoding="utf-8"))
        bad = []
        for k in GUARDED:
            if s[k] > base[k]:
                bad.append("%s rose: %d > baseline %d" % (k, s[k], base[k]))
        card = CORPUS / "SCORECARD.md"
        if not card.exists() or card.read_text(encoding="utf-8") != markdown(s):
            bad.append("SCORECARD.md is stale; run --write")
        for m in bad:
            print("FAIL:", m)
        return 1 if bad else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
